import asyncio
import ccxt.async_support as ccxt
import pandas as pd

async def analizar_simbolo(exchange, symbol, semaphore):
    async with semaphore:
        try:
            # Descargar últimas 50 velas de 1 hora
            velas = await exchange.fetch_ohlcv(symbol, timeframe='1h', limit=50)
            if len(velas) < 30:
                return None

            df = pd.DataFrame(velas, columns=['timestamp', 'open', 'high', 'low', 'close', 'volume'])
            close = df['close']
            precio_actual = close.iloc[-1]

            # 1. CÁLCULO DE RSI (14)
            delta = close.diff()
            gain = (delta.where(delta > 0, 0)).rolling(14).mean()
            loss = (-delta.where(delta < 0, 0)).rolling(14).mean()
            rs = gain / loss
            rsi = 100 - (100 / (1 + rs))
            rsi_actual = rsi.iloc[-1]

            # 2. CÁLCULO DE MACD (12, 26, 9)
            exp1 = close.ewm(span=12, adjust=False).mean()
            exp2 = close.ewm(span=26, adjust=False).mean()
            macd_line = exp1 - exp2
            signal_line = macd_line.ewm(span=9, adjust=False).mean()
            macd_hist = (macd_line - signal_line).iloc[-1]

            # 3. CÁLCULO DE BANDAS DE BOLLINGER (20, 2)
            sma_20 = close.rolling(20).mean()
            std_20 = close.rolling(20).std()
            upper_band = sma_20 + (2 * std_20)
            lower_band = sma_20 - (2 * std_20)

            upper = upper_band.iloc[-1]
            lower = lower_band.iloc[-1]
            sma = sma_20.iloc[-1]

            # 4. VOLUMEN
            volumen_actual = df['volume'].iloc[-1]
            volumen_promedio = df['volume'].rolling(20).mean().iloc[-1]

            # --- SISTEMA DE PUNTUACIÓN DE PROBABILIDAD ---
            puntos_alcistas = 50  # Base neutral (50/50)

            # A. Evaluación MACD
            if macd_hist > 0:
                puntos_alcistas += 15
            else:
                puntos_alcistas -= 15

            # B. Evaluación Bandas de Bollinger
            if precio_actual <= lower * 1.01:
                puntos_alcistas += 20
            elif precio_actual >= upper * 0.99:
                puntos_alcistas -= 20
            elif precio_actual > sma:
                puntos_alcistas += 5

            # C. Evaluación RSI
            if rsi_actual < 30:
                puntos_alcistas += 15
            elif rsi_actual > 70:
                puntos_alcistas -= 15

            # D. Confirmación de Volumen
            if volumen_actual > (volumen_promedio * 1.5):
                if macd_hist > 0:
                    puntos_alcistas += 10
                else:
                    puntos_alcistas -= 10

            prob_subir = max(0, min(100, int(puntos_alcistas)))
            prob_bajar = 100 - prob_subir

            return {
                'symbol': symbol,
                'precio': precio_actual,
                'prob_subir': prob_subir,
                'prob_bajar': prob_bajar,
                'rsi': rsi_actual,
                'macd': macd_hist
            }

        except Exception:
            return None

async def main():
    # Cambiamos a MEXC para evitar el bloqueo por región en la nube
    exchange = ccxt.mexc({
        'enableRateLimit': True,
        'options': {'defaultType': 'spot'}
    })

    print("Conectando con MEXC para cargar mercados...")
    markets = await exchange.load_markets()

    simbolos = [s for s, m in markets.items() if s.endswith('/USDT') and m['active']]
    print(f"Se encontraron {len(simbolos)} pares USDT. Iniciando escaneo avanzado...")
    print("=" * 75)
    print(f"{'CRIPTO':<12} | {'PRECIO':<10} | {'PROB. SUBIR':<12} | {'PROB. BAJAR':<12} | {'RSI':<6}")
    print("=" * 75)

    semaphore = asyncio.Semaphore(10)

    tareas = [analizar_simbolo(exchange, s, semaphore) for s in simbolos]
    resultados = await asyncio.gather(*tareas)

    resultados_validos = [r for r in resultados if r is not None]
    resultados_validos.sort(key=lambda x: x['prob_subir'], reverse=True)

    candidatos_destacados = 0
    for res in resultados_validos:
        if res['prob_subir'] >= 75 or res['prob_bajar'] >= 75:
            candidatos_destacados += 1
            tendencia = "🚀 ALCISTA" if res['prob_subir'] >= 75 else "🔻 BAJISTA"
            print(f"{res['symbol']:<12} | ${res['precio']:>9.2f} | {res['prob_subir']:>10}% | {res['prob_bajar']:>10}% | {res['rsi']:>5.1f} | {tendencia}")

    print("=" * 75)
    print(f"Escaneo finalizado. Se encontraron {candidatos_destacados} criptos con alta probabilidad (>75%).")

    await exchange.close()

await main()

